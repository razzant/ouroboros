"""Write ``web/modules/unicode_case_folding.js``, the case folding chat search matches with, from Unicode's own table.

The source is ``scripts/unicode/CaseFolding-17.0.0.txt``, copied byte for byte from
https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt (SHA-256 below; Unicode License v3,
``scripts/unicode/LICENSE.txt``). The module keeps the default full case folding, every line of status
C and F and none of S (the simple alternative of an F line) or T (Turkic dotless i): a code point the
table does not list folds to itself. One pinned table serves every browser engine alike, whatever
Unicode version its own ``toLowerCase`` or the host's Python knows (``web/modules/chat_search_words.js``).

``python scripts/generate_case_folding.py`` rewrites the module; ``--check`` exits 1 when the committed
module differs from what the source generates. A source whose bytes differ from the pin is refused:
changing the Unicode version is a reviewed change of this pin, the file name and the module together.
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "unicode" / "CaseFolding-17.0.0.txt"
MODULE = ROOT / "web" / "modules" / "unicode_case_folding.js"
VERSION = "17.0.0"
SOURCE_URL = f"https://www.unicode.org/Public/{VERSION}/ucd/CaseFolding.txt"
SOURCE_SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"
_PER_LINE = 12


def folding(data: bytes) -> dict[int, tuple[int, ...]]:
    """The C and F lines of a CaseFolding.txt as ``{code point: folded code points}``."""
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise SystemExit(f"{SOURCE.name}: bytes differ from the pinned Unicode {VERSION} table")
    table: dict[int, tuple[int, ...]] = {}
    for line in data.decode("utf-8").splitlines():
        fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
        if len(fields) < 3 or fields[1] not in ("C", "F"):
            continue
        code = int(fields[0], 16)
        if code in table:
            raise SystemExit(f"{SOURCE.name}: U+{code:04X} has two default foldings")
        table[code] = tuple(int(part, 16) for part in fields[2].split())
    return table


def render(table: dict[int, tuple[int, ...]]) -> str:
    entries = [f"{code:X}:{' '.join(f'{part:X}' for part in table[code])}" for code in sorted(table)]
    lines = ["    '" + ";".join(entries[at:at + _PER_LINE]) + "'," for at in range(0, len(entries), _PER_LINE)]
    return "\n".join([
        "// GENERATED by scripts/generate_case_folding.py from scripts/unicode/CaseFolding-17.0.0.txt; do not edit.",
        f"// Unicode {VERSION} CaseFolding.txt ({SOURCE_URL}), SHA-256 {SOURCE_SHA256}.",
        "// © Unicode, Inc., Unicode License v3 (scripts/unicode/LICENSE.txt).",
        "// Default full case folding: status C and F, never S or T. Each entry is `code:folded code points`, hexadecimal;",
        "// a code point not listed folds to itself.",
        f"export const UNICODE_VERSION = '{VERSION}';",
        f"export const CASE_FOLDING_ENTRIES = {len(entries)};",
        "export const CASE_FOLDING = [",
        *lines,
        "].join(';');",
        "",
    ])


def main(argv: list[str]) -> int:
    expected = render(folding(SOURCE.read_bytes()))
    if argv[1:] == ["--check"]:
        if MODULE.read_text(encoding="utf-8") != expected:
            print(f"{MODULE.relative_to(ROOT)} differs from {SOURCE.relative_to(ROOT)}; run without --check", file=sys.stderr)
            return 1
        return 0
    if argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    MODULE.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
