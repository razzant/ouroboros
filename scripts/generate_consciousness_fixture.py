"""Generate browser wake/history fixtures through the store and Python producers.

Run from the repository root with an isolated OUROBOROS_DATA_DIR. The real old
wake is unchanged; named variants explicitly exercise the new optional facts.
"""
import contextlib
import copy
import datetime as dt
import json
from pathlib import Path
import tempfile
from unittest.mock import patch

from ouroboros import consciousness_view as view, dialogue_store, store, usage_accounting, usage_store
from ouroboros.gateway.history import _assemble_history_response
from ouroboros.icon_geometry import icon_spec
from ouroboros.terminal_projection import _project_row
from ouroboros.tool_call_log import append_call_row
from tests._store_shared import seed_result

REPO = Path(__file__).resolve().parents[1]
NOW = dt.datetime(2026, 10, 24, 8, tzinfo=dt.timezone.utc).timestamp()
SENTENCE = "Проверил состояние системы и сохранил наблюдения; нового решения от тебя не требуется."


def seed_terminal_history(root, row):
    """A terminal-only page: an old summary beside the current hidden projection.

    The legacy row predates quiet/summary metadata; its immutable terminal
    observation supplies those facts. One typed tool-log event makes its card
    visible without any progress row, through the actual history evidence reader.
    """
    terminal = _project_row(row["task_id"], row, {}, {"chat_id": 1})
    legacy = {key: value for key, value in terminal.items() if key not in (
        "summary_kind", "outcome_authority", "quiet_effective", "wake_silent", "wake_summary", "suggested_name")}
    legacy.update(summary_id="legacy:" + row["task_id"], ts="2026-10-24T07:49:00+00:00")
    append_call_row({}, root / "logs", {"task_id": row["task_id"], "ts": legacy["ts"],
        "type": "tool_call", "tool": "run_command", "invocation_id": row["task_id"] + "-call", "is_error": False})
    dialogue_store.append(root, "chat", legacy)
    dialogue_store.append(root, "chat", terminal)


def generate():
    fixture = json.loads((REPO / "tests/fixtures/consciousness_controls.json").read_text(encoding="utf-8"))
    document = json.loads((REPO / "tests/fixtures/wake_document_214a31b6.json").read_text(encoding="utf-8"))
    fixture["_comment"] = "Generated by scripts/generate_consciousness_fixture.py; do not edit."
    snapshot = fixture["state"]["bg_consciousness_state"]
    snapshot.update(next_wake_at="2026-10-24T09:30:00+00:00", appointment_at="2026-10-24T09:30:00+00:00",
                    live_wake_held=False, last_wake_outcome="completed")
    # The producer shows server-local time: pin the fixture's clock and its display zone at the producer's own
    # seam, never through the process zone (POSIX-only tzset; it would also reach every other thread).
    with patch.object(view.time, "time", return_value=NOW), patch.object(view, "_DISPLAY_ZONE", dt.timezone.utc):
        snapshot = view.describe_consciousness_state(snapshot, True)
    fixture["state"]["bg_consciousness_state"] = snapshot
    with tempfile.TemporaryDirectory(prefix="wake-fixture-") as temporary, contextlib.ExitStack() as release:
        root = Path(temporary)
        release.callback(store.close_connections_under, root)  # Windows removes no open file: hand the stores back first
        documents = []
        variants = [(document["task_id"], {}), ("w-summary", {
            "wake_summary": SENTENCE, "suggested_name": SENTENCE, "tool_calls": 16,
            "safety_checks": [{"chip": chip, "tool": tool} for chip, tool in [
                ("checked", "run_command"), ("not_checked", "update_memory"),
                ("warned", "run_script"), ("held", "place_reply"), ("sent_despite", "slack_send")]],
        }), ("w-spoke", {"owner_message_sent": True})]
        variants += [("w-focus-" + kind, {"metadata": {
            **document.get("metadata", {}), "wake_cause": "focus", "focus": {
                "place_id": "mail", "conversation_key": "mail:account:inbox:0",
                "identity": {"sends_as": {"id": "writer", "label": label, "kind": kind}},
                "identity_owner": kind == "user"}}})
            for kind, label in (("user", "Human mailbox"), ("bot", "Ouroboros bot"))]
        variants += [("w-" + phase, {"status": phase, "suggested_name": "Own time"})
                     for phase in ("running", "waiting", "queued", "paused", "unknown")]
        for index, (task_id, fields) in enumerate(variants):
            row = copy.deepcopy(document)
            row.update(fields)
            row.update(task_id=task_id, root_task_id=task_id, budget_drive_root=str(root))
            row["execution_owner"].update(task_id=task_id, data_root=str(root))
            if "status" in fields:
                for key in ("terminal_time", "loop_outcome", "outcome_axes", "result", "wake_silent", "terminal_origin"):
                    row.pop(key, None)
                row["cost_presentation"] = {"scope": "root_tree", "tracked_amount": 0.02,
                    "has_unpriced": False, "tracked_final": False, "accounting_open": True, "has_rows": True}
            if task_id == "w-waiting":
                row.update(status="running", owner_wait={"state": "waiting", "quiz_id": "q1"})
            stored = seed_result(root, task_id, row)
            documents.append(stored)
            stamp = dt.datetime.fromtimestamp(NOW - 60 + index, dt.timezone.utc).isoformat()
            with patch.object(usage_store, "utc_now_iso", return_value=stamp):
                usage_accounting.record_unmetered_external_dispatch(task_id, drive_root=root,
                    task_id=task_id, root_task_id=task_id, category="consciousness")
        fixture["consciousness"] = {**snapshot, "recent_wakes": view.recent_wakes(root, [], now=NOW),
            "recent_wakes_coverage": "wakes that reached a model call in the last 48 h"}
        with patch("ouroboros.terminal_projection.utc_now_iso", return_value="2026-10-24T07:50:00+00:00"):
            for row in documents[:3]:
                seed_terminal_history(root, row)
        fixture["history"] = json.loads(_assemble_history_response(root, 1, 50, 200))
        # A real checkpoint-only replay: no terminal summary and no task_named frame.
        dialogue_store.append(root, "progress", {"task_id": "w-running", "chat_id": 1,
            "type": "task_checkpoint", "system_type": "task_checkpoint", "ts": "2026-10-24T07:59:00+00:00", "status": "running",
            "initiator": "consciousness", "content": "Checking the system", "rounds": 1})
        fixture["running_history"] = json.loads(_assemble_history_response(root, 1, 50, 200))
        fixture["running_history"]["messages"] = [row for row in fixture["running_history"]["messages"]
                                                   if row.get("task_id") == "w-running"]
        fixture["terminal_only_history"] = []
        for sent in (False, True):
            terminal_root = root / ("spoke" if sent else "quiet")
            stored = seed_result(terminal_root, document["task_id"], {**document, "owner_message_sent": sent})
            with patch("ouroboros.terminal_projection.utc_now_iso", return_value="2026-10-24T07:50:00+00:00"):
                seed_terminal_history(terminal_root, stored)
            fixture["terminal_only_history"].append(json.loads(_assemble_history_response(terminal_root, 1, 50, 200)))
    # These are the same icon producer bytes used by PlaceSummary and catalog rows.
    for row in fixture["places"]["places"] + fixture["places"]["connectors"]:
        old = row.get("icon") or {}
        row["icon"] = icon_spec("ui/icon.svg", old["svg"]) if old.get("svg") else icon_spec(old.get("name", ""))
    for row in fixture["places"]["places"]:
        row.setdefault("revision", 1)
    return fixture


if __name__ == "__main__":
    target = REPO / "web/tests/fixtures/consciousness_contract.json"
    target.write_text(json.dumps(generate(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(target.relative_to(REPO))
