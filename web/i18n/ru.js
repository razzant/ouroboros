export function plural(n, one, few, many) {
  const a = Math.abs(Number(n));
  if (!Number.isFinite(a)) return many;
  if (!Number.isInteger(a)) return few;
  const m10 = a % 10;
  const m100 = a % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

