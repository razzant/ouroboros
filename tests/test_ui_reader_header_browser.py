import pytest

pytestmark = [pytest.mark.ui_browser, pytest.mark.serial]
ROOT = Path(__file__).resolve().parents[1]
CAPTION = ("A detailed image caption with context and explanation. " * 35).replace(". ", ".\n", 2)
ORDINARY = "owner-portrait-screenshot-of-the-settings-page-with-a-long-descriptive-name.png"
# Wide, unbroken text exercises the bound even within the existing 200-character display limit.
LONG_NAME = "W" * 190 + ".png"

HARNESS = """<!doctype html><html class="ouro-ui" lang="en"><head>
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="stylesheet" href="/web/ui.css"><link rel="stylesheet" href="/web/style.css">
</head><body><main id="fixture"></main></body></html>"""

MOUNT = """async ({kind, name}) => {
    const {createChatMedia} = await import('/web/modules/chat_media.js');
    window.media?.destroy();
    const fixture = document.querySelector('#fixture');
    fixture.replaceChildren();
    window.media = createChatMedia({chatSessionId: 'geometry', durableChatMediaUrl: x => x,
        formatMsgTime: () => null, senderLabel: () => 'You', stampNodeTimestamp: () => {},
        insertMessageNode: node => fixture.append(node)});
    // A real 700 x 1300 PNG with text, generated by the browser's canvas encoder.
    const canvas = document.createElement('canvas');
    canvas.width = 700; canvas.height = 1300;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = '#f0f4fa'; ctx.fillRect(0, 0, 700, 1300);
    ctx.fillStyle = '#203048'; ctx.font = '28px sans-serif';
    for (let y = 55; y < 1300; y += 65) ctx.fillText(`Reader geometry · row ${y}`, 28, y);
    window.fixtureImage = canvas.toDataURL('image/png');
    const image = window.fixtureImage.split(',')[1];
    const bubble = kind === 'photo'
        ? media.buildMediaBubble({type: 'photo', role: 'assistant', mime: 'image/png',
            image_base64: image, caption: name})
        : media.buildDocumentBubble({type: 'document', role: 'assistant',
            mime: {text: 'text/plain', markdown: 'text/markdown'}[kind] || 'image/png', filename: name,
            file_base64: kind === 'image' ? image : btoa('The complete text body.\\n'.repeat(100))});
    fixture.append(bubble);
    window.openerTile = fixture.querySelector('.chat-photo-open, .chat-file-card');
    window.openerTile.click();
}"""

STATE = """() => {
    const dialog = document.querySelector('dialog.document-reader[open]');
    const title = dialog.querySelector('.document-reader-title');
    const body = dialog.querySelector('.document-reader-body');
    const image = body.querySelector('img');
    const box = el => { const r = el.getBoundingClientRect();
        return {x:r.x, y:r.y, width:r.width, height:r.height, right:r.right, bottom:r.bottom}; };
    return {viewport: [innerWidth, innerHeight], dialog: box(dialog),
        head: box(dialog.querySelector('header')), title: box(title), name: title.textContent,
        titleHeight: [title.clientHeight, title.scrollHeight], titleScroll: title.scrollTop,
        whiteSpace: getComputedStyle(title).whiteSpace,
        body: box(body), bodyScroll: [body.scrollLeft, body.scrollTop],
        image: image ? box(image) : null, natural: image ? [image.naturalWidth, image.naturalHeight] : null,
        active: document.activeElement.className, theme: document.documentElement.dataset.theme,
        dialogCount: document.querySelectorAll('dialog[open]').length,
        caption: document.querySelector('figcaption')?.textContent,
        labelled: dialog.getAttribute('aria-labelledby') === title.id,
        buttons: [...dialog.querySelectorAll('header button')].filter(b => b.getClientRects().length).map(b => {
            const r = box(b); return {label: b.textContent, ...r,
                hit: b.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2))};
        }), opened: window.opened, bodyText: body.textContent};
}"""


@pytest.fixture
def component_url():
    class StaticConsumer(SimpleHTTPRequestHandler):
        def do_GET(self):
            if self.path == "/":
                data = HARNESS.encode()
                self.send_response(200)
                self.send_header("Content-Type", "text/html")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
            else:
                super().do_GET()

        def log_message(self, *_):
            pass

    server = ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(StaticConsumer, directory=str(ROOT)))
    worker = Thread(target=server.serve_forever, daemon=True)
    worker.start()
    try:
        yield f"http://127.0.0.1:{server.server_port}"
    finally:
        server.shutdown()
        server.server_close()
        worker.join()


def _check_geometry(state):
    width, height = state["viewport"]
    assert state["dialogCount"] == 1 and state["labelled"] and state["opened"] == [], state
    for button in state["buttons"]:
        assert button["hit"] and button["x"] >= 0 and button["y"] >= 0, button
        assert button["right"] <= width + 1 and button["bottom"] <= height + 1, button
    assert state["head"]["y"] >= state["dialog"]["y"] - 1, state
    assert state["body"]["y"] >= state["head"]["bottom"] - 1, state
    assert state["body"]["height"] >= state["dialog"]["height"] * 0.4, state
    if state["image"]:
        image, body = state["image"], state["body"]
        assert state["natural"] == [700, 1300], state
        assert image["height"] > 200 and image["width"] > 100, state
        assert image["x"] >= body["x"] and image["right"] <= body["right"] + 1, state
        assert image["y"] >= body["y"] and image["bottom"] <= body["bottom"] + 1, state


@pytest.mark.parametrize("engine", ["chromium", "webkit"])
def test_long_reader_title_keeps_controls_and_content_reachable(component_url, tmp_path, engine):
    from playwright.sync_api import sync_playwright

    evidence = Path(os.environ.get("OUROBOROS_UI_EVIDENCE_DIR", str(tmp_path / "evidence")))
    evidence.mkdir(parents=True, exist_ok=True)
    records = {}
    errors = []
    with sync_playwright() as playwright:
        browser = getattr(playwright, engine).launch()
        page = browser.new_page()
        # macOS WebKit's normal Tab skips buttons; Option-Tab includes them.
        tab = "Alt+Tab" if engine == "webkit" else "Tab"
        page.on("pageerror", lambda error: errors.append(str(error)))
        try:
            records["browser"] = browser.version
            # The reported 621px failure first, then the phone and normal desktop.
            for width in (621, 390, 1280):
                for theme in ("dark", "light"):
                    page.set_viewport_size({"width": width, "height": 844})
                    page.goto(component_url)
                    page.evaluate("theme => {document.documentElement.dataset.theme = theme; "
                                  "window.opened = []; window.open = (...args) => opened.push(args);}", theme)
                    for case, kind, name in (("caption", "photo", CAPTION), ("ordinary", "image", ORDINARY),
                                             ("long-name", "image", LONG_NAME), ("text", "text", LONG_NAME + ".txt")):
                        key = f"{engine}-{width}-{theme}-{case}"
                        page.evaluate(MOUNT, {"kind": kind, "name": name})
                        page.wait_for_function("() => document.querySelector('.document-reader-body')?.getAttribute('aria-busy') === 'false'")
                        page.wait_for_timeout(700)
                        state = page.evaluate(STATE)
                        records[key] = {"fit": state}
                        page.screenshot(path=str(evidence / f"{key}-fit.png"))
                        assert state["name"] == name, state
                        assert state["active"].startswith("document-reader-body"), state
                        if kind == "photo":
                            assert state["caption"] == CAPTION and len(CAPTION) == 1925, state
                            assert state["whiteSpace"] == "pre-wrap", state
                        _check_geometry(state)
                        if case == "ordinary":
                            assert state["titleHeight"][1] <= state["titleHeight"][0] + 1, state
                        if kind == "text":
                            assert state["bodyText"] == "The complete text body.\n" * 100, state
                        # Body starts focused. Tab wraps to the title, which must let a
                        # keyboard user read all overflowing text without moving the header.
                        page.keyboard.press(tab)
                        assert page.locator(".document-reader-title").evaluate("n => n === document.activeElement")
                        if state["titleHeight"][1] > state["titleHeight"][0] + 1:
                            page.keyboard.press("End")
                            page.wait_for_function("() => {const t = document.querySelector('.document-reader-title'); "
                                                   "return t.scrollTop + t.clientHeight >= t.scrollHeight - 1;}")
                            records[key]["title_end"] = page.evaluate(STATE)
                            _check_geometry(records[key]["title_end"])
                            page.screenshot(path=str(evidence / f"{key}-title-end.png"))
                        # Every visible header control is in the keyboard cycle.
                        focused = []
                        for _ in state["buttons"]:
                            page.keyboard.press(tab)
                            focused.append(page.evaluate("() => document.activeElement.textContent"))
                        assert focused == [button["label"] for button in state["buttons"]], focused
                        page.keyboard.press(tab)
                        assert page.locator(".document-reader-body").evaluate("n => n === document.activeElement")
                        records[key]["tab_order"] = focused
                        if kind != "text":
                            page.locator('[data-reader-view="actual"]').click()
                            body = page.locator(".document-reader-body")
                            body.focus()
                            page.keyboard.press("PageDown")
                            page.wait_for_function("() => document.querySelector('.document-reader-body').scrollTop > 0")
                            actual = page.evaluate(STATE)
                            assert [actual["image"]["width"], actual["image"]["height"]] == [700, 1300], actual
                            records[key]["actual"] = actual
                        if case in ("caption", "text"):
                            page.locator('[data-reader-action="close"]').click()
                        else:
                            page.keyboard.press("Escape")
                        page.locator("dialog.document-reader").wait_for(state="detached")
                        returned = page.evaluate("() => document.activeElement === window.openerTile")
                        records[key]["focus_returned"] = returned
                        assert returned
            assert not errors, errors
        finally:
            records["page_errors"] = errors
            (evidence / f"{engine}-geometry.json").write_text(json.dumps(records, indent=2) + "\n")
            browser.close()


@pytest.mark.parametrize("engine", ["chromium", "webkit"])
@pytest.mark.parametrize("gesture", ["pointer", "keyboard"])
def test_clipped_photo_menu_view_keeps_place_and_returns_focus(component_url, tmp_path, engine, gesture):
    """A menu's View must not reveal its clipped summary before opening the reader."""
    from playwright.sync_api import sync_playwright

    evidence = Path(os.environ.get("OUROBOROS_UI_EVIDENCE_DIR", str(tmp_path / "evidence")))
    evidence.mkdir(parents=True, exist_ok=True)
    key, records = f"{engine}-{gesture}-clipped-menu", {}
    measure = """() => {
        const feed = document.querySelector('#fixture');
        const summary = feed.querySelector('summary');
        return {scroll: feed.scrollTop, top: summary.getBoundingClientRect().top,
            hidden: feed.getBoundingClientRect().top - summary.getBoundingClientRect().top,
            returned: document.activeElement === summary};
    }"""
    with sync_playwright() as playwright:
        browser = getattr(playwright, engine).launch()
        page = browser.new_page(viewport={"width": 621, "height": 844})
        try:
            page.goto(component_url)
            page.evaluate(MOUNT, {"kind": "photo", "name": "Clipped menu photo"})
            page.locator('.document-reader-image').wait_for()
            page.keyboard.press("Escape")
            page.locator('dialog.document-reader').wait_for(state="detached")
            page.add_style_tag(content="""#fixture { height: 500px; overflow: auto; }
                #fixture::before, #fixture::after { content: ''; display: block; height: 700px; }""")
            summary = page.locator('#fixture .chat-photo-actions summary')
            summary.evaluate("""node => {
                node.focus({preventScroll: true});
                const feed = document.querySelector('#fixture');
                feed.scrollTop += node.getBoundingClientRect().top - feed.getBoundingClientRect().top + 10;
            }""")
            before = records['before'] = page.evaluate(measure)
            assert abs(before['hidden'] - 10) <= 1, before
            if gesture == "pointer":
                box = summary.bounding_box()
                page.mouse.click(box['x'] + box['width'] / 2, box['y'] + box['height'] - 5)
            else:
                page.keyboard.press("Enter")
            view = page.locator('.chat-photo-menu:not([hidden]) [data-photo-action="view"]')
            view.wait_for(state="visible")
            records['menu'] = page.evaluate(measure)
            assert abs(records['menu']['scroll'] - before['scroll']) <= 1, records
            page.screenshot(path=str(evidence / f'{key}-menu.png'))
            if gesture == "pointer":
                view.click()
            else:
                assert view.evaluate('node => node === document.activeElement')
                page.keyboard.press("Enter")
            page.wait_for_function("() => document.querySelector('.document-reader-image')?.naturalWidth > 0")
            records['reader'] = page.evaluate(measure)
            page.screenshot(path=str(evidence / f'{key}-reader.png'))
            assert abs(records['reader']['scroll'] - before['scroll']) <= 1, records
            page.keyboard.press("Escape")
            page.locator('dialog.document-reader').wait_for(state="detached")
            after = records['after'] = page.evaluate(measure)
            assert after['returned'], records
            assert abs(after['scroll'] - before['scroll']) <= 1 and abs(after['top'] - before['top']) <= 1, records
        finally:
            (evidence / f'{key}.json').write_text(json.dumps(records, indent=2) + '\n')
            browser.close()


GROUPS = """() => {
    const dialog = document.querySelector('dialog.document-reader[open]');
    const box = el => { const r = el.getBoundingClientRect();
        return {top: Math.round(r.top), bottom: Math.round(r.bottom), left: Math.round(r.left), right: Math.round(r.right)}; };
    const group = selector => [...dialog.querySelectorAll(`${selector} button`)].filter(b => b.getClientRects().length)
        .map(b => { const r = box(b); return {label: b.textContent, ...r,
            hit: b.contains(document.elementFromPoint((r.left + r.right) / 2, (r.top + r.bottom) / 2))}; });
    const head = dialog.querySelector('.document-reader-head');
    return {width: innerWidth, head: box(head), headOverflow: head.scrollWidth - head.clientWidth,
        close: box(dialog.querySelector('.document-reader-close')), views: group('.document-reader-views'),
        file: group('.document-reader-file'), menus: dialog.querySelectorAll('[role="menu"], [aria-haspopup="menu"]').length};
}"""


@pytest.mark.parametrize("engine", ["chromium", "webkit"])
def test_phone_reader_keeps_every_action_in_sight_in_two_groups(component_url, tmp_path, engine):
    """#5: on a phone the name has its row beside Close and every action stays in sight under it, the view first and
    the file's own actions after it: one row when both groups fit (a reviewer's answer: Formatted, Source, Download),
    one row each when they do not (a photo's five). A group never splits and nothing goes under a menu."""
    from playwright.sync_api import sync_playwright

    evidence = Path(os.environ.get("OUROBOROS_UI_EVIDENCE_DIR", str(tmp_path / "evidence")))
    evidence.mkdir(parents=True, exist_ok=True)
    records, errors = {}, []
    with sync_playwright() as playwright:
        browser = getattr(playwright, engine).launch()
        page = browser.new_page(has_touch=True)
        page.on("pageerror", lambda error: errors.append(str(error)))
        try:
            for width in (390, 1280):
                for theme in ("light", "dark"):
                    page.set_viewport_size({"width": width, "height": 844})
                    page.goto(component_url)
                    page.evaluate("theme => { document.documentElement.dataset.theme = theme; }", theme)
                    for case, kind, name in (("answer", "markdown", "claude-opus-5-5 · answer.md"),
                                             ("photo", "photo", "A short photo caption")):
                        key = f"{engine}-{width}-{theme}-{case}"
                        page.evaluate(MOUNT, {"kind": kind, "name": name})
                        page.wait_for_function("() => document.querySelector('.document-reader-body')?.getAttribute('aria-busy') === 'false'")
                        page.wait_for_timeout(300)
                        state = records[key] = page.evaluate(GROUPS)
                        page.screenshot(path=str(evidence / f"{key}-groups.png"))
                        views, file = state["views"], state["file"]
                        expected = (["Formatted", "Source"], ["Download"]) if case == "answer" else (
                            ["Fit", "Actual size"], ["Copy", "Open", "Download"])
                        assert ([b["label"] for b in views], [b["label"] for b in file]) == expected, state
                        assert state["menus"] == 0 and state["headOverflow"] <= 1, state
                        for button in views + file:
                            assert button["hit"] and button["left"] >= 0 and button["right"] <= width + 1, state
                        # A group is one row; the file's actions never come before the view.
                        assert len({b["top"] for b in views}) == 1 and len({b["top"] for b in file}) == 1, state
                        assert file[0]["top"] >= views[0]["top"], state
                        if width == 390:
                            # Actions are under the name's row (Close), and only as many rows as the groups need.
                            assert views[0]["top"] >= state["close"]["bottom"], state
                            if case == "answer":
                                assert file[0]["top"] == views[0]["top"], state
                                assert state["head"]["bottom"] - state["head"]["top"] <= 100, state
                            else:
                                assert file[0]["top"] >= views[0]["bottom"], state
                        else:
                            # The desk keeps its one head row: the actions beside Close.
                            assert abs(views[0]["top"] - state["close"]["top"]) <= 1, state
                            assert file[0]["top"] == views[0]["top"], state
                        page.keyboard.press("Escape")
                        page.locator("dialog.document-reader").wait_for(state="detached")
            assert not errors, errors
        finally:
            (evidence / f"{engine}-groups.json").write_text(json.dumps(records, indent=2) + "\n")
            browser.close()
