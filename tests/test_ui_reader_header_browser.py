"""Reader header geometry with production media/reader modules and CSS, no SPA/server.

A local static consumer opens the actual photo tile/file card. This is a layout
falsifier, not coverage of delivery, routing, the desktop bridge or chat history.
Run this file with the browser marker; evidence is kept in OUROBOROS_UI_EVIDENCE_DIR.
"""
from __future__ import annotations

import functools
